class ProcessRunner:
    """One tracked subprocess slot: start (SSE-streamed), stop, status.
    Two independent instances are used -- `main` (single-shot install/build/
    launch commands) and `agent` (the long-lived micro-ROS agent) -- so the
    agent can keep running while a Bringup/Teleop/SLAM command uses `main`.
    """

    def __init__(self, name):
        self.name = name
        self.process = None
        self.lock = threading.Lock()

    def is_busy(self):
        with self.lock:
            return self.process is not None and self.process.poll() is None

    def start_streaming(self, command, cwd, send_event):
        with self.lock:
            if self.process is not None and self.process.poll() is None:
                return False
            env = os.environ.copy()
            env["PYTHONUNBUFFERED"] = "1"
            self.process = subprocess.Popen(
                ["bash", "-lc", command],
                cwd=cwd,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                env=env,
                preexec_fn=os.setsid,
            )
        proc = self.process
        try:
            for line in iter(proc.stdout.readline, ""):
                if not line:
                    break
                send_event("output", {"line": line.rstrip("\n")})
        finally:
            proc.wait()
            exit_code = proc.returncode
            with self.lock:
                if self.process is proc:
                    self.process = None
            send_event("done", {"exit_code": exit_code})
        return True

    def kill(self):
        with self.lock:
            proc = self.process
            if proc is None or proc.poll() is not None:
                return False
            try:
                os.killpg(os.getpgid(proc.pid), signal.SIGTERM)
                proc.wait(timeout=5)
            except Exception:
                try:
                    os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
                except Exception:
                    pass
            self.process = None
            return True



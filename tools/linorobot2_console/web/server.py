    driver = "MOTOR_DRIVER_MDD10A"
    if "l298" in d or "l298n" in d: driver = "MOTOR_DRIVER_L298"
    elif "tb6612" in d: driver = "MOTOR_DRIVER_TB6612FNG"
    elif "bts7960" in d: driver = "MOTOR_DRIVER_BTS7960"


def parse_unified_yaml(text):
    sections = {}
    current_section = None
    current_lines = []

    for line in text.splitlines():
        line_clean = line.strip()
        if not line_clean or line_clean.startswith("#"):
            if current_section:
                current_lines.append(line)
            continue
        if ":" in line:
            parts = line.split(":", 1)
            key = parts[0].strip()
            indent = len(line) - len(line.lstrip())
            if indent == 0 and key in ("linorobot2", "nav2", "ekf", "slam"):
                if current_section:
                    sections[current_section] = "\n".join(current_lines)
                current_section = key
                current_lines = []
                continue
            elif indent == 0 and key in ("amcl", "bt_navigator", "controller_server", "planner_server",
                                         "behavior_server", "local_costmap", "global_costmap",
                                         "waypoint_follower", "velocity_smoother", "map_server"):
                if current_section != "nav2":
                    if current_section:
                        sections[current_section] = "\n".join(current_lines)
                    current_section = "nav2"
                    current_lines = []
            elif indent == 0 and key == "ekf_filter_node":
                if current_section:
                    sections[current_section] = "\n".join(current_lines)
                current_section = "ekf"
                current_lines = []
            elif indent == 0 and key == "slam_toolbox":
                if current_section:
                    sections[current_section] = "\n".join(current_lines)
                current_section = "slam"
                current_lines = []

        if current_section:
            current_lines.append(line)

    if current_section:
        sections[current_section] = "\n".join(current_lines)

    def deindent(sec_text):
        lines = sec_text.splitlines()
        indents = [len(l) - len(l.lstrip()) for l in lines if l.strip() and not l.strip().startswith("#")]
        if indents:
            min_indent = min(indents)
            if min_indent > 0:
                return "\n".join(l[min_indent:] if len(l) >= min_indent else l for l in lines)
        return sec_text

    lino_cfg = {}
    if "linorobot2" in sections:
        for line in sections["linorobot2"].splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if ":" in line:
                k, v = line.split(":", 1)
                k = k.strip()
                v = v.split("#")[0].strip().strip("'\"")
                if v.lower() == "true":
                    lino_cfg[k] = True
                elif v.lower() == "false":
                    lino_cfg[k] = False
                elif v.isdigit():
                    lino_cfg[k] = int(v)
                else:
                    lino_cfg[k] = v

    return {
        "linorobot2": lino_cfg,
        "nav2": deindent(sections.get("nav2", "")).strip(),
        "ekf": deindent(sections.get("ekf", "")).strip(),
        "slam": deindent(sections.get("slam", "")).strip(),
    }


